// Generates tests/manual-checklist.md from docs/user-stories.md, so the
// checklist always lists every v1 criterion with its exact wording.
// Run it again whenever the user stories change:  node scripts/make-checklist.js

import { readFileSync, writeFileSync } from 'node:fs';

const storiesUrl = new URL('../docs/user-stories.md', import.meta.url);
const checklistUrl = new URL('../tests/manual-checklist.md', import.meta.url);

// v1 stories, in the order the technical plan builds them (D-27).
const V1 = ['S-1', 'S-2', 'S-3', 'S-10', 'S-5', 'S-6', 'S-7'];

// Criteria checked in Firefox as well as Chrome (definition of done).
const SMOKE = new Set([
  'S-1.2', 'S-1.8', 'S-1.26', 'S-1.29', 'S-1.34', 'S-2.4', 'S-2.8', 'S-3.2', 'S-3.4', 'S-3.16',
  'S-10.3', 'S-10.15', 'S-5.3', 'S-5.4', 'S-5.8', 'S-5.20', 'S-5.28', 'S-6.1', 'S-6.10', 'S-7.1', 'S-7.9',
]);

// Checks that come from the brief and the technical plan rather than one criterion.
const EXTRA = [
  ['X-1', '**Keyboard only.** Without the mouse, complete S-1.2, then S-6.1. Tab reaches every field and button in order, arrow keys change the mode and the tip, Enter or Space presses buttons, and the focus ring is always visible.', true],
  ['X-2', "**Phone width.** In the browser's device toolbar at 360px wide, both modes with results showing fit with no sideways scrolling, and the table shows one card per person.", true],
  ['X-3', '**Reload (D-22).** Enter values in both modes, then reload the page. Every field is back to the opening state (S-1.1), with no old values restored.', true],
  ['X-4', '**Pasted HTML name (D-24).** Name a person `<img src=x onerror=alert(1)>`. It shows as plain text, and no pop-up appears.', false],
  ['X-5', '**Never NaN or blank.** During all of the above, the page never shows NaN, Infinity, undefined or an empty result.', true],
  ['X-6', "**Typing is never interrupted (D-21).** Type a long amount quickly in a field and in a person's Ordered field. The cursor never jumps and no characters are lost.", false],
];

// Keep the results already recorded: the Chrome and Firefox cells of every row
// whose ID still exists, and the "Date and browser version" row. Without this,
// running the script after a change to the stories would wipe every tick.
const recorded = new Map();
let recordedDates = null;
try {
  for (const line of readFileSync(checklistUrl, 'utf8').split('\n')) {
    const cells = line.split(' | ');
    const id = /^\| ((?:S-\d+\.\d+)|(?:X-\d+)) \|/.exec(line)?.[1];
    if (id && cells.length >= 5) recorded.set(id, cells.slice(-2).join(' | ').replace(/ \|$/, ''));
    if (line.startsWith('| Date and browser version |')) recordedDates = line;
  }
} catch {
  // No checklist yet: start with empty results.
}

const lines = readFileSync(storiesUrl, 'utf8').split('\n');
const titles = {};
const criteria = Object.fromEntries(V1.map((story) => [story, []]));
let current = null;

lines.forEach((line, index) => {
  const heading = /^### (S-\d+): (.*)/.exec(line);
  if (heading) {
    current = heading[1];
    titles[current] = heading[2];
    return;
  }
  const criterion = /^- \*\*(S-\d+\.\d+)\*\* (.*)/.exec(line);
  if (!criterion || !(current in criteria)) return;
  let text = criterion[2].replace(/:$/, '');
  const subBullets = [];
  for (let next = index + 1; lines[next]?.startsWith('  - '); next++) subBullets.push(lines[next].slice(4));
  if (subBullets.length) text += ': ' + subBullets.join('; ');
  criteria[current].push([criterion[1], text.replaceAll('|', '\\|')]);
});

const total = V1.reduce((sum, story) => sum + criteria[story].length, 0);
const unknownSmoke = [...SMOKE].filter((id) => !V1.some((s) => criteria[s].some(([cid]) => cid === id)));
if (unknownSmoke.length) throw new Error(`Smoke IDs not found in the user stories: ${unknownSmoke.join(', ')}`);

const row = (id, text, smoke) =>
  `| ${id} | ${text} | ${smoke ? 'smoke' : ''} | ${recorded.get(id) ?? `[ ] | ${smoke ? '[ ]' : '–'}`} |`;
const out = [
  '# Manual checklist',
  '',
  '<!-- Generated by scripts/make-checklist.js from docs/user-stories.md. Do not edit the criterion text by hand: change the stories and run the script again. Results in the Chrome and Firefox columns are recorded by hand, and the script keeps them when it runs again. -->',
  '',
  'Hand checks for the definition of done in `docs/scope-and-decisions.md`.',
  '',
  '- **Chrome:** check every criterion. Write the date and browser version at the top of the column the first time, then tick each row.',
  '- **Firefox:** check only the rows marked **smoke**, plus the smoke extra checks at the end.',
  '- A criterion that fails stays unticked. Note what you saw, and report it by ID.',
  '',
  `Criteria are copied from \`docs/user-stories.md\` (${total} v1 criteria, ${SMOKE.size} marked smoke). The full wording there is the reference.`,
  '',
  'Start the app with `npm start` and open http://localhost:8080. Use **Reset** between criteria.',
  '',
  '**How to check S-1.34 by hand** (a value filled in without typing): with results showing for subtotal `100`, open the browser console (F12) and run',
  '`const f = document.getElementById("subtotal"); f.value = "500"; f.dispatchEvent(new Event("change", { bubbles: true }));`',
  'This is how some autofill tools and password managers fill a field. The results must then show "Subtotal 500.00".',
  '',
  '| | Chrome | Firefox |',
  '|---|---|---|',
  recordedDates ?? '| Date and browser version | | |',
  '',
];
for (const story of V1) {
  out.push(`## ${story}: ${titles[story]}`, '', '| ID | What to check | Smoke | Chrome | Firefox |', '|---|---|---|---|---|');
  for (const [id, text] of criteria[story]) out.push(row(id, text, SMOKE.has(id)));
  out.push('');
}
out.push('## Extra checks', '', 'These come from the brief and the technical plan, not from a single criterion.', '',
  '| ID | What to check | Smoke | Chrome | Firefox |', '|---|---|---|---|---|');
for (const [id, text, smoke] of EXTRA) out.push(row(id, text, smoke));
out.push('');

writeFileSync(checklistUrl, out.join('\n'));
console.log(`Wrote tests/manual-checklist.md: ${total} v1 criteria, ${SMOKE.size} smoke, ${EXTRA.length} extra checks.`);
